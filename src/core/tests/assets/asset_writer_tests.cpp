std::span<const std::byte> bytesOf(const std::string& s)
{
    return std::as_bytes(std::span(s.data(), s.size()));
}

std::uint64_t sumOf(const std::vector<std::uint8_t>& v)
{
    return std::accumulate(v.begin(), v.end(), std::uint64_t{ 0 });
}

sed::assets::CmpPalette cubePalette()
{
    sed::assets::CmpPalette p{};
    for (int i = 0; i < 256; ++i)
        p[static_cast<std::size_t>(i)] = { static_cast<std::uint8_t>((i & 7) * 36),
            static_cast<std::uint8_t>(((i >> 3) & 7) * 36), static_cast<std::uint8_t>((i >> 6) * 85) };
    return p;
}

