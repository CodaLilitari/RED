void runAssetWriterTests()
{
    using namespace sed::assets;
    {
        const RgbaImage image = decodePng(bytesOf(kPngRgbDynamic));
        check(image.width == 32 && image.height == 16, "png: dynamic-Huffman RGB dimensions");
        check(sumOf(image.rgba) == 294328u, "png: dynamic-Huffman RGB pixels match the encoder's");
        const std::size_t at = (3u * 32u + 5u) * 4u;
        check(image.rgba[at] == 40 && image.rgba[at + 1] == 48 && image.rgba[at + 2] == 200 && image.rgba[at + 3] == 255,
            "png: pixel (5,3) decodes exactly");
    }
    {
        const RgbaImage image = decodePng(bytesOf(kPngPaletteTrns));
        check(image.width == 8 && image.height == 8 && sumOf(image.rgba) == 36720u,
            "png: palette image with transparency decodes");
        // (x + y) % 4 == 3 is the transparent index
        check(image.rgba[(0u * 8u + 3u) * 4u + 3u] == 0 && image.rgba[3] == 255,
            "png: tRNS alpha applies to its palette index only");
    }
    {
        // RED's own encoder (stored or compressed blocks) round-trips.
        std::vector<std::uint8_t> rgba(16u * 8u * 4u);
        for (std::size_t i = 0; i < rgba.size(); ++i) rgba[i] = static_cast<std::uint8_t>((i * 37u) & 0xFFu);
        const auto png = sed::render::encodePngRgba8(16, 8, rgba);
        const RgbaImage image = decodePng(std::as_bytes(std::span(png.data(), png.size())));
        check(image.width == 16 && image.height == 8 && image.rgba == rgba, "png: RED's encoder round-trips exactly");
    }
    {
        std::string broken = kPngRgbDynamic;
        broken[broken.size() / 2] ^= 0x40;
        bool threw = false;
        try { (void)decodePng(bytesOf(broken)); } catch (const std::runtime_error&) { threw = true; }
        check(threw, "png: a damaged file is refused, not guessed");
        threw = false;
        try { (void)decodePng(bytesOf(std::string("not a png at all"))); } catch (const std::runtime_error&) { threw = true; }
        check(threw, "png: a non-PNG is refused");
    }
    {
        const CmpPalette palette = cubePalette();
        const RgbaImage image = decodePng(bytesOf(kPngRgbDynamic));
        IndexedMatOptions options;
        options.dither = false;
        const IndexedMatResult built = buildIndexedMat({ image, image }, palette, options);
        check(built.report.width == 32 && built.report.height == 16 && built.report.cels == 2
                && built.report.mipmaps == 2, "mat write: report matches (mipmaps clamp to an 8-pixel level)");
        std::vector<std::byte> raw(built.bytes.size());
        std::memcpy(raw.data(), built.bytes.data(), built.bytes.size());
        const MatFile mat = MatFile::parse(std::move(raw), &palette);
        check(mat.celCount() == 2 && mat.cels()[0].width == 32 && mat.cels()[0].height == 16
                && mat.cels()[0].mipmaps.size() == 2, "mat write: the MAT reader loads what was written");
        const auto decoded = mat.decodeCelRgba8(0);
        bool inPalette = true;
        for (std::size_t i = 0; i < decoded.rgba.size(); i += 4)
        {
            bool found = false;
            for (const CmpColor& c : palette)
                found = found || (c.r == decoded.rgba[i] && c.g == decoded.rgba[i + 1] && c.b == decoded.rgba[i + 2]);
            inPalette = inPalette && found;
        }
        check(inPalette, "mat write: every pixel is a palette colour");

        // A palette-exact image maps back to itself with zero error.
        RgbaImage exact;
        exact.width = 8;
        exact.height = 8;
        for (int i = 0; i < 64; ++i)
        {
            const CmpColor& c = palette[static_cast<std::size_t>(i * 4)];
            exact.rgba.insert(exact.rgba.end(), { c.r, c.g, c.b, 255 });
        }
        const IndexedMatResult same = buildIndexedMat({ exact }, palette, options);
        check(same.report.meanError == 0.0 && same.report.mipmaps == 1,
            "mat write: palette colours map to themselves exactly");
        bool refused = false;
        RgbaImage odd = exact;
        odd.width = 12;
        odd.height = 8;
        odd.rgba.resize(12u * 8u * 4u);
        try { (void)buildIndexedMat({ odd }, palette, options); } catch (const std::invalid_argument&) { refused = true; }
        check(refused, "mat write: a width that is not a power of two is refused");
        refused = false;
        try { (void)buildIndexedMat({ exact, image }, palette, options); } catch (const std::invalid_argument&) { refused = true; }
        check(refused, "mat write: cels of different sizes are refused");
    }
    {
        const std::string bytes = buildGobBytes({ { "mat/a.mat", "AAAA" }, { "cog\\b.cog", "symbols\nend\n" } });
        std::vector<std::byte> raw(bytes.size());
        std::memcpy(raw.data(), bytes.data(), bytes.size());
        const GobArchive gob = GobArchive::fromBytes(std::move(raw), "test.gob");
        check(gob.entries().size() == 2 && gob.entries()[0].name == "mat\\a.mat" && gob.entries()[0].size == 4,
            "gob write: entries keep their order and use backslashes");
    }
}

